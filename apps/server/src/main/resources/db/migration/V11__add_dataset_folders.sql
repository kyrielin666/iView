CREATE TABLE iview_dataset_folder (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    folder_name VARCHAR(100) NOT NULL,
    parent_id BIGINT,
    description VARCHAR(500) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_iview_dataset_folder_parent FOREIGN KEY (parent_id) REFERENCES iview_dataset_folder(id) ON DELETE RESTRICT
);

ALTER TABLE iview_dataset ADD folder_id BIGINT;
ALTER TABLE iview_dataset ADD CONSTRAINT fk_iview_dataset_folder FOREIGN KEY (folder_id) REFERENCES iview_dataset_folder(id) ON DELETE RESTRICT;
