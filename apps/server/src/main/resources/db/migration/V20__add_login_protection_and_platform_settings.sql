CREATE TABLE iview_auth_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(64) NOT NULL,
    remote_address VARCHAR(64) NOT NULL,
    successful BOOLEAN NOT NULL,
    reason VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_iview_auth_audit_created ON iview_auth_audit(created_at);
CREATE INDEX idx_iview_auth_audit_username ON iview_auth_audit(username);

CREATE TABLE iview_system_parameter (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parameter_key VARCHAR(128) NOT NULL UNIQUE,
    parameter_value VARCHAR(2000) NOT NULL DEFAULT '',
    value_type VARCHAR(32) NOT NULL DEFAULT 'string',
    description VARCHAR(500) NOT NULL DEFAULT '',
    public_visible BOOLEAN NOT NULL DEFAULT FALSE,
    updated_by BIGINT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (updated_by) REFERENCES iview_user(id) ON DELETE SET NULL
);

CREATE TABLE iview_navigation_menu (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    menu_code VARCHAR(64) NOT NULL UNIQUE,
    parent_code VARCHAR(64),
    menu_label VARCHAR(100) NOT NULL,
    route VARCHAR(200) NOT NULL,
    icon VARCHAR(64) NOT NULL DEFAULT '',
    sort_order INTEGER NOT NULL DEFAULT 0,
    permission_code VARCHAR(128),
    enabled BOOLEAN NOT NULL DEFAULT TRUE
);

