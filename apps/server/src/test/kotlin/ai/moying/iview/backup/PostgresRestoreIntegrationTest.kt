package ai.moying.iview.backup

import ai.moying.iview.datasource.PostgresLineageCatalog
import ai.moying.iview.datasource.HeatmapAggregation
import ai.moying.iview.datasource.PostgresStructuredQueryBuilder
import ai.moying.iview.datasource.SchemaColumn
import ai.moying.iview.datasource.SqlSemanticLineageAnalyzer
import org.flywaydb.core.Flyway
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.condition.EnabledIfEnvironmentVariable
import org.junit.jupiter.api.io.TempDir
import org.springframework.jdbc.core.JdbcTemplate
import org.springframework.jdbc.datasource.DriverManagerDataSource
import java.net.URI
import java.nio.file.Path
import java.sql.DriverManager
import java.util.UUID
import kotlin.test.*

/** Explicit opt-in. Creates and drops only its own random database; never restores the admin DB. */
@EnabledIfEnvironmentVariable(named = "IVIEW_PG_REHEARSAL", matches = "true")
class PostgresRestoreIntegrationTest {
    @TempDir lateinit var directory: Path

    @Test fun `real postgres restores application schema rows constraints sequences and rolls back failed restores`() {
        fun required(name: String) = requireNotNull(System.getenv(name)?.takeIf { it.isNotBlank() }) { "Missing $name" }
        val adminUrl = required("IVIEW_PG_REHEARSAL_ADMIN_URL")
        require(adminUrl.startsWith("jdbc:postgresql://"))
        val uri = URI(adminUrl.removePrefix("jdbc:"))
        require(uri.rawQuery == null && uri.userInfo == null) { "Use separate credentials and a plain isolated test connection" }
        val user = required("IVIEW_PG_REHEARSAL_USER")
        val password = required("IVIEW_PG_REHEARSAL_PASSWORD")
        val database = "iview_rehearsal_" + UUID.randomUUID().toString().replace("-", "")
        val targetUrl = "jdbc:" + URI(uri.scheme, null, uri.host, uri.port, "/$database", null, null)
        DriverManager.getConnection(adminUrl, user, password).use { admin ->
            admin.createStatement().use { it.execute("CREATE DATABASE $database") }
            try {
                val source = DriverManagerDataSource(targetUrl, user, password)
                val jdbc = JdbcTemplate(source)
                val flyway = Flyway.configure().dataSource(source).locations("classpath:db/migration", "classpath:db/vendor/postgresql").load()
                flyway.migrate()
                jdbc.execute("CREATE TABLE rehearsal_parent(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT UNIQUE NOT NULL)")
                jdbc.execute("CREATE TABLE rehearsal_child(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, parent_id BIGINT REFERENCES rehearsal_parent(id), amount NUMERIC(12,2), payload JSONB, observed_at TIMESTAMPTZ)")
                jdbc.execute("CREATE TABLE rehearsal_case(\"Ä\" INTEGER, \"ä\" INTEGER)")
                jdbc.execute("CREATE TABLE rehearsal_heatmap(shift_name TEXT, machine_name TEXT, quantity INTEGER)")
                jdbc.execute("INSERT INTO rehearsal_heatmap SELECT '早班','一号机',1 FROM generate_series(1,101)")
                jdbc.execute("INSERT INTO rehearsal_heatmap VALUES (NULL,'无效机',1), ('','空班次',1), ('晚班','二号机',NULL)")
                jdbc.execute("CREATE INDEX rehearsal_amount_idx ON rehearsal_child(amount)")
                jdbc.execute("INSERT INTO rehearsal_parent(name) VALUES('设备甲'),('设备乙')")
                jdbc.execute("INSERT INTO rehearsal_child(parent_id,amount,payload,observed_at) VALUES(1,12.50,'{\"state\":\"运行\"}','2026-10-09T00:00:00Z'),(2,0.00,NULL,NULL)")
                fun snapshot() = jdbc.queryForList("SELECT p.id,p.name,c.amount,c.payload::text AS payload,c.observed_at::text AS observed_at FROM rehearsal_parent p JOIN rehearsal_child c ON c.parent_id=p.id ORDER BY p.id")
                val expected = snapshot()
                val heatmapQuery = PostgresStructuredQueryBuilder().build(
                    "SELECT shift_name,machine_name,quantity FROM rehearsal_heatmap", emptyList(),
                    listOf(SchemaColumn("shift_name", "TEXT", false), SchemaColumn("machine_name", "TEXT", false), SchemaColumn("quantity", "INTEGER", false)),
                    HeatmapAggregation.postgresRequest("shift_name", "machine_name", "quantity", emptyMap()))
                assertEquals("101", jdbc.queryForList(heatmapQuery.sql).single()["iview_heatmap_sum"].toString())
                assertEquals(1, jdbc.queryForObject(heatmapQuery.countSql, Int::class.java))
                // Exercises production catalog resolution, including the connection's search_path.
                source.connection.use { connection ->
                    val lineage = SqlSemanticLineageAnalyzer.analyze("SELECT sum(c.amount) AS total FROM rehearsal_child c JOIN rehearsal_parent p ON p.id=c.parent_id", PostgresLineageCatalog(connection)::resolve)
                    assertEquals("amount", lineage.outputs.single().sources.single().column)
                    assertTrue(lineage.warnings.isEmpty())
                    val caseLineage = SqlSemanticLineageAnalyzer.analyze("SELECT Ä FROM rehearsal_case", PostgresLineageCatalog(connection)::resolve)
                    assertEquals("Ä", caseLineage.outputs.single().sources.single().column)
                }
                val backups = BackupService(jdbc, targetUrl, user, password, directory.toString(), 7, true, true,
                    required("IVIEW_PG_DUMP"), required("IVIEW_PG_RESTORE"), 120, NativePostgresCommandExecutor())
                val backup = backups.create()
                assertTrue(backups.validate(backup.name).valid)
                jdbc.update("UPDATE rehearsal_parent SET name='changed' WHERE id=1")
                jdbc.execute("CREATE VIEW rehearsal_blocker AS SELECT * FROM rehearsal_parent")
                val beforeFailure = snapshot()
                // The new dependent view prevents --clean from dropping the backed-up parent table.
                assertFailsWith<BackupException> { backups.restore(backup.name, "RESTORE ${backup.name}") }
                assertEquals(beforeFailure, snapshot(), "A failed restore must leave all pre-restore rows intact")
                jdbc.execute("DROP VIEW rehearsal_blocker")
                backups.restore(backup.name, "RESTORE ${backup.name}")
                assertEquals(expected, snapshot())
                flyway.validate()
                assertEquals(3L, jdbc.queryForObject("INSERT INTO rehearsal_parent(name) VALUES('after restore') RETURNING id", Long::class.java))
                assertFailsWith<org.springframework.dao.DataIntegrityViolationException> { jdbc.update("INSERT INTO rehearsal_child(parent_id) VALUES(9999)") }
                assertEquals(1, jdbc.queryForObject("SELECT count(*) FROM pg_indexes WHERE indexname='rehearsal_amount_idx'", Int::class.java))
            } finally {
                admin.createStatement().use { it.execute("DROP DATABASE $database") }
            }
        }
    }
}
